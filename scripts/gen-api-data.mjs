#!/usr/bin/env node
// Writes api/_carddata.ts: the compact card database the serverless functions need.
// Vercel functions can't import the app's JSON at runtime, so we generate a TS module.
// Run after sync-data (sync-data.mjs calls this automatically).
import { readFile, writeFile } from 'node:fs/promises';

const cards = JSON.parse(await readFile(new URL('../src/data/cards.json', import.meta.url), 'utf8'));
const slim = cards
  .filter((c) => c.ram != null && (c.text || c.type === 'Legend') && c.legal === 'legal')
  .map((c) => ({ slug: c.slug, name: c.name, display: c.display, color: c.color, type: c.type, cost: c.cost, power: c.power, ram: c.ram, sellable: c.sellable, traits: c.traits, text: c.text }));
await writeFile(
  new URL('../api/_carddata.ts', import.meta.url),
  `// Generated by scripts/gen-api-data.mjs. Do not edit.\nexport interface ApiCard { slug: string; name: string; display: string; color: string; type: string; cost: number | null; power: number | null; ram: number; sellable: boolean; traits: string[]; text: string }\nexport const API_CARDS: ApiCard[] = ${JSON.stringify(slim)};\n`,
);
console.log(`api/_carddata.ts: ${slim.length} cards`);
